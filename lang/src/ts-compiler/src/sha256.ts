/*
  Pure-TS SHA-256 (hex digest of a string's UTF-8 bytes).

  Replaces node's crypto.createHash('sha256') so the compile pipeline
  (anf-loop-compiler's function-name mangling, compile-lib's standalone
  uri table, cli-module-loader's cache file names) has no node-only
  dependency and can be bundled for the browser. Output is identical to
  crypto.createHash('sha256').update(s, 'utf8').digest('hex').
*/

